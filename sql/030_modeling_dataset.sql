CLUSTER BY crop_name, PROVINCE
OPTIONS (
  description = "One row per crop x province x harvest year. Climate features aggregated over JRC crop phases, static territorial characteristics, current and one-year-lagged production."
)
AS

WITH climate_monthly AS (
  SELECT
    PROVINCE,
    YEAR_MONTH,
    CAST(SUBSTR(YEAR_MONTH, 1, 4) AS INT64) AS calendar_year,
    CAST(SUBSTR(YEAR_MONTH, 6, 2) AS INT64) AS calendar_month,
    * EXCEPT (PROVINCE, YEAR_MONTH)
  FROM `agriclimate-intelligence.curated.climate_full_dataset_v1`
),

-- Number of calendar months each crop phase is expected to contain.
expected_months AS (
  SELECT
    crop_name,
    COUNTIF(phase = 'planting_early_vegetative') AS expected_months__planting_early_vegetative,
    COUNTIF(phase = 'ripening_harvest') AS expected_months__ripening_harvest,
    COUNTIF(phase = 'vegetative_reproductive') AS expected_months__vegetative_reproductive
  FROM `agriclimate-intelligence.utilities.crop_calendar`
  GROUP BY crop_name
