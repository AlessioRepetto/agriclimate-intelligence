-- BigQuery Standard SQL script used to materialize the modelling dataset.
--
-- Phase-level climate aggregation expressions were generated
-- programmatically during development from the project aggregation rules,
-- then reviewed and executed directly in BigQuery.
--
-- The expressions in this file correspond to the climate schema and
-- aggregation policy used for the final project dataset.
-- If either changes, the phase-level feature definitions must be reviewed
-- before rebuilding the table.
--
-- Reproduces the transformation pipeline of EDA_AgriClimate_Intelligence:
-- crop calendar -> phase aggregation -> pivot -> production join -> lag 1.

DECLARE min_harvest_year INT64 DEFAULT 1995;
DECLARE max_harvest_year INT64 DEFAULT 2022;

